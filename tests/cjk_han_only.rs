#![cfg(not(target_family = "wasm"))]

//! Runs every word in `tests/data/cjk_han_only_test_set.tsv` through a
//! detector for all languages. The test set is generated by
//! `scripts/generate_cjk_han_only_test_set.py` and holds real Chinese and
//! Japanese words in five classes: Chinese-only, Japanese-only, shared
//! characters combined with Chinese-only or Japanese-only ones, and words
//! written only with characters both languages use, which must be reported
//! as `Language::Ambiguous` rather than as either language.

use std::collections::BTreeMap;

use lingua::{Language, LanguageDetectorBuilder};

const TEST_SET: &str = include_str!("data/cjk_han_only_test_set.tsv");

#[test]
fn test_han_only_text_is_detected_according_to_its_characters() {
    let detector = LanguageDetectorBuilder::from_all_languages().build();
    let mut totals = BTreeMap::<&str, usize>::new();
    let mut failures = BTreeMap::<&str, Vec<String>>::new();

    for line in TEST_SET.lines().skip(1) {
        let [class, origin, text, expected] = line.split('\t').collect::<Vec<_>>()[..] else {
            panic!("malformed line: {line:?}");
        };
        let expected = match expected {
            "Chinese" => Some(Language::Chinese),
            "Japanese" => Some(Language::Japanese),
            "Ambiguous" => Some(Language::Ambiguous),
            other => panic!("unknown expected language {other:?}"),
        };
        *totals.entry(class).or_default() += 1;

        let detected = detector.detect_language_of(text);
        if detected != expected {
            failures.entry(class).or_default().push(format!(
                "{text} ({origin}): expected {expected:?}, got {detected:?}"
            ));
        }
    }

    for class in [
        "chinese_only",
        "common_with_chinese",
        "japanese_only",
        "common_with_japanese",
        "common",
    ] {
        let total = totals.get(class).copied().unwrap_or(0);
        assert!(total >= 100, "class {class} has only {total} samples");
    }

    let report = failures
        .iter()
        .map(|(class, cases)| {
            format!(
                "{class}: {} of {} failed\n  {}",
                cases.len(),
                totals[class],
                cases.join("\n  ")
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    assert!(failures.is_empty(), "{report}");
}
